"""Stand-in for the ACSS 3 framework in the offline preview / page builder.

Only what the templates read from ACSS is simulated: colours, the fluid text / heading / space / section-space
scales, radius, gaps, the base reset + typography, section padding and the btn--* buttons. Values are close to
ACSS 3 defaults, not identical — check the real site in Etch before going live.

Every length is written in px and converted with the page's root font size (like ACSS does with its
"root font size" setting), so the preview looks the same at 1rem = 10px and 1rem = 16px. If a template changes
size when you switch the root in the builder, it uses a raw rem value somewhere."""

MIN_VW, MAX_VW = 360, 1400  # fluid values grow between these viewport widths


def px(n):
    return f"calc({n:g} * var(--px))"


def fluid(lo, hi):
    slope = (hi - lo) / (MAX_VW - MIN_VW)
    base = lo - slope * MIN_VW
    return f"clamp({px(lo)}, {px(round(base, 2))} + {slope * 100:.3f}vw, {px(hi)})"


COLORS = {
    "primary": "#1e3a5f", "secondary": "#e8a33d", "accent": "#0e7c66", "base": "#1a1a1a", "neutral": "#6b7280",
    "white": "#ffffff", "black": "#000000", "text-dark": "#1a1a1a", "text-light": "#f5f5f5",
    "warning-dark": "#7a4b00", "warning-light": "#ffd88a", "warning-ultra-light": "#fff6e0",
}
TEXT = {"xs": (12, 13), "s": (14, 15), "m": (16, 18), "l": (19, 22), "xl": (22, 28), "xxl": (26, 36)}
HEAD = {"h1": (34, 56), "h2": (28, 44), "h3": (23, 33), "h4": (20, 26), "h5": (18, 21), "h6": (16, 18)}
SPACE = {"3xs": (4, 5), "2xs": (6, 8), "xs": (8, 12), "s": (14, 20), "m": (20, 30), "l": (28, 44), "xl": (40, 64),
         "2xl": (56, 96)}
SECTION = {"xs": (24, 40), "s": (40, 60), "m": (56, 96), "l": (72, 128), "xl": (88, 160)}
RADIUS = {"xs": 4, "s": 6, "m": 10, "l": 16, "xl": 24}


def css():
    v = ["--px: calc(1rem / var(--etch-root-px, 10));"]
    v += [f"--{k}: {c};" for k, c in COLORS.items()]
    v += [f"--{k}-hover: color-mix(in srgb, var(--{k}) 85%, black);" for k in ("primary", "secondary", "accent")]
    v += [f"--text-{k}: {fluid(*r)};" for k, r in TEXT.items()]
    v += [f"--{k}: {fluid(*r)};" for k, r in HEAD.items()]
    v += [f"--space-{k}: {fluid(*r)};" for k, r in SPACE.items()]
    v += ["--space-xxl: var(--space-2xl);"]
    v += [f"--section-space-{k}: {fluid(*r)};" for k, r in SECTION.items()]
    v += [f"--radius-{k}: {px(r)};" for k, r in RADIUS.items()]
    v += ["--radius: var(--radius-m);", "--radius-circle: 999px;",
          f"--gutter: {fluid(16, 40)};", f"--content-width: {px(1366)};",
          "--grid-gap: var(--space-m);", "--container-gap: var(--space-xl);", "--content-gap: var(--space-m);",
          "--text-color: var(--text-dark);", "--body-bg-color: var(--white);",
          "--border-light: color-mix(in srgb, var(--black) 12%, transparent);",
          f"--box-shadow-l: 0 {px(12)} {px(32)} color-mix(in srgb, var(--black) 16%, transparent);",
          f"--btn-padding-block: {px(12)};", f"--btn-padding-inline: {px(26)};",
          "--btn-border-radius: var(--radius-s);", f"--btn-border-width: {px(2)};", "--btn-font-weight: 600;",
          "--btn-text-transform: none;"]
    root = "\n  ".join(v)
    return f"""/* ACSS 3 stand-in for the offline preview — generated by _build/acss_sim.py */
:root {{
  {root}
}}

*, *::before, *::after {{ box-sizing: border-box; }}
html {{ font-size: 62.5%; -webkit-text-size-adjust: 100%; }}
body {{
  margin: 0;
  background: var(--body-bg-color);
  color: var(--text-color);
  font-family: system-ui, -apple-system, "Segoe UI", Roboto, "Noto Sans Thai", "Sukhumvit Set", Tahoma, sans-serif;
  font-size: var(--text-m);
  line-height: 1.6;
  -webkit-font-smoothing: antialiased;
}}
:where(h1, h2, h3, h4, h5, h6, p, figure, blockquote, dl, dd, ul, ol) {{ margin: 0; }}
:where(h1, h2, h3, h4, h5, h6) {{ line-height: 1.2; font-weight: 700; text-wrap: balance; }}
h1 {{ font-size: var(--h1); }} h2 {{ font-size: var(--h2); }} h3 {{ font-size: var(--h3); }}
h4 {{ font-size: var(--h4); }} h5 {{ font-size: var(--h5); }} h6 {{ font-size: var(--h6); }}
:where(img, svg, video, iframe) {{ max-inline-size: 100%; }}
:where(img) {{ display: block; block-size: auto; }}
:where(a) {{ color: var(--primary); }}
:where(button, input, select, textarea) {{ font: inherit; }}
:where(button) {{ padding: 0; border: 0; background: none; color: inherit; cursor: pointer; }}
:where(button:not(nav button)) {{ font-weight: var(--btn-font-weight); text-transform: var(--btn-text-transform); }}
:where(blockquote) {{ padding-inline-start: var(--space-m); border-inline-start: {px(4)} solid var(--border-light); }}

/* ACSS section padding */
:where(section:not(section section)) {{
  padding-block: var(--section-space-m);
  padding-inline: var(--gutter);
}}

/* ACSS utilities used by the kit */
.clickable-parent::after {{ content: ""; position: absolute; inset: 0; }}

/* ACSS buttons */
:where([class*="btn--"]) {{
  --btn-bg: var(--primary);
  --btn-text: var(--white);
  --btn-bg-hover: var(--primary-hover);
  display: inline-flex;
  align-items: center;
  justify-content: center;
  gap: var(--space-xs);
  padding: var(--btn-padding-block) var(--btn-padding-inline);
  border: var(--btn-border-width) solid var(--btn-bg);
  border-radius: var(--btn-border-radius);
  background-color: var(--btn-bg);
  color: var(--btn-text);
  font-size: var(--text-m);
  font-weight: var(--btn-font-weight);
  line-height: 1.2;
  text-align: center;
  text-decoration: none;
  text-transform: var(--btn-text-transform);
  cursor: pointer;
  transition: background-color .2s ease, border-color .2s ease, color .2s ease;
}}
:where([class*="btn--"]):hover {{ background-color: var(--btn-bg-hover); border-color: var(--btn-bg-hover); }}
/* --pv-btn-*-text: button text colour picked in the page builder (ACSS sets it on the real site) */
.btn--primary {{ --btn-bg: var(--primary); --btn-text: var(--pv-btn-primary-text, var(--white)); --btn-bg-hover: var(--primary-hover); }}
.btn--secondary {{ --btn-bg: var(--secondary); --btn-text: var(--pv-btn-secondary-text, var(--black)); --btn-bg-hover: var(--secondary-hover); }}
.btn--accent {{ --btn-bg: var(--accent); --btn-text: var(--white); --btn-bg-hover: var(--accent-hover); }}
.btn--outline {{ background-color: transparent; color: var(--btn-bg); }}
.btn--outline:hover {{ background-color: var(--btn-bg); border-color: var(--btn-bg); color: var(--btn-text); }}
.btn--secondary.btn--outline {{ color: var(--btn-bg); }}
"""
